local function applyStorageToAllPlayers(storageKey, storageValue)
	return db.query(string.format([[
		INSERT INTO `player_storage` (`player_id`, `key`, `value`)
		SELECT `id`, %d, %d FROM `players`
		ON DUPLICATE KEY UPDATE `value` = VALUES(`value`);
	]], storageKey, storageValue))
end

function onUpdateDatabase()
	logger.info("Updating database to version 62 (grant Eclipse baseline quest access)")

	for _, access in ipairs(freeQuestAccess) do
		if not applyStorageToAllPlayers(access.key, access.value) then
			logger.error("Failed to grant free quest access: " .. access.name)
			return false
		end
	end

	if not applyStorageToAllPlayers(30057, 2) then
		logger.error("Failed to mark free quest access stage 2.")
		return false
	end

	return true
end
